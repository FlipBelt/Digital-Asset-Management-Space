import assert from "node:assert/strict";
import { contactCustodians, contactDepartments, contactIdentifier, parseContactRows } from "../frontend/src/lib/contactRegistration.ts";

const people = [{ id: "p1", display_name: "惜君-测试员工", employment_status: "active", legal_entity_id: "c1", department_id: "d1" },
  { id: "p2", display_name: "离职-测试员工", employment_status: "departed", legal_entity_id: "c1", department_id: "d1" }];
const departments = [{ id: "d1", name: "信息技术部", legal_entity_id: "c1" }];
const identities = [{ identifier: "18958354558", version: 6 }];
const parse = (text, rows = people) => parseContactRows(text, rows, departments, identities, "c1");
assert.equal(contactIdentifier("+86 189-5835-4558"), "18958354558");
assert.equal(contactIdentifier("Test@Example.COM"), "test@example.com");
assert.equal(contactIdentifier("not-a-phone"), null);
const source = parse("18958354558\t惜君\t技术部\t宁波");
assert.equal(source.errors.length, 0);
assert.equal(source.rows[0].custodian_person_id, "p1");
assert.equal(source.rows[0].expected_version, 6);
assert.equal(source.rows[0].owner_department_id, "d1");
const shared = parse("17365822471\t转发器\t技术部\t共用转发");
assert.equal(shared.rows[0].custodian_person_id, null);
assert.equal(shared.rows[0].owner_department_id, "d1");
assert.equal(parse("17365822471\t前台手机\t不存在的部门").errors.length, 1);
assert.equal(parse("18958354558\t离职\t技术部").errors.length, 1);
assert.equal(parse("18958354558\t惜君\t技术部", [...people, { ...people[0], id: "ambiguous" }]).errors.length, 1);
assert.equal(parse("18958354558\t惜君\t技术部\t法人手机号（勿用）").rows[0].registration_blocked, true);
assert.equal(parse("18958354558\t惜君\t技术部\n+8618958354558\t惜君\t技术部").errors.length, 1);
assert.deepEqual(contactCustodians(people, "business-company", true).map(row => row.id), ["p1"]);
assert.deepEqual(contactCustodians(people, "business-company").map(row => row.id), []);
assert.deepEqual(contactDepartments(departments, "business-company", true).map(row => row.id), ["d1"]);
assert.deepEqual(contactDepartments(departments, "business-company").map(row => row.id), []);
const crossCompany = parseContactRows("holder@example.invalid\t惜君\t技术部", people, departments, [], "business-company", true);
assert.equal(crossCompany.errors.length, 0);
assert.equal(crossCompany.rows[0].legal_entity_id, "business-company");
assert.equal(crossCompany.rows[0].custodian_person_id, "p1");
assert.equal(crossCompany.rows[0].owner_department_id, "d1");
const crossShared = parseContactRows("shared@example.invalid\t共用\t技术部", people, departments, [], "business-company", true);
assert.equal(crossShared.errors.length, 0);
assert.equal(crossShared.rows[0].legal_entity_id, "business-company");
assert.equal(crossShared.rows[0].owner_department_id, "d1");
assert.equal(parseContactRows("holder@example.invalid\t惜君\t技术部", people, departments, [], "business-company").errors.length, 1);
assert.equal(parseContactRows("shared@example.invalid\t共用\t技术部", people, departments, [], "business-company").errors.length, 1);
const duplicatePeople = [...people, { ...people[0], id: "p3", legal_entity_id: "c2", department_id: "d2" }];
const duplicateDepartments = [...departments, { ...departments[0], id: "d2", legal_entity_id: "c2" }];
const companyPriority = parseContactRows("holder@example.invalid\t惜君\t技术部", duplicatePeople, duplicateDepartments, [], "c1", true);
assert.equal(companyPriority.errors.length, 0);
assert.equal(companyPriority.rows[0].custodian_person_id, "p1");
assert.equal(companyPriority.rows[0].owner_department_id, "d1");
assert.equal(companyPriority.rows[0].legal_entity_id, "c1");
const sharedCompanyPriority = parseContactRows("shared@example.invalid\t共用\t技术部", duplicatePeople, duplicateDepartments, [], "c1", true);
assert.equal(sharedCompanyPriority.errors.length, 0);
assert.equal(sharedCompanyPriority.rows[0].owner_department_id, "d1");
const ambiguousCrossPerson = parseContactRows("holder@example.invalid\t惜君\t技术部", duplicatePeople, departments, [], "business-company", true);
assert.equal(ambiguousCrossPerson.errors.length, 1);
assert.equal(ambiguousCrossPerson.rows.length, 0);
const ambiguousCrossShared = parseContactRows("shared@example.invalid\t共用\t技术部", people, duplicateDepartments, [], "business-company", true);
assert.equal(ambiguousCrossShared.errors.length, 1);
assert.equal(ambiguousCrossShared.rows.length, 0);
const ambiguousCrossDepartment = parseContactRows("holder@example.invalid\t惜君\t技术部", people, duplicateDepartments, [], "business-company", true);
assert.equal(ambiguousCrossDepartment.errors.length, 1);
assert.equal(ambiguousCrossDepartment.rows.length, 0);
assert.equal(parseContactRows("holder@example.invalid\t惜君\t技术部", [...people, { ...people[0], id: "ambiguous" }], departments, [], "c1", true).errors.length, 1);
assert.equal(parseContactRows("shared@example.invalid\t共用\t技术部", people, [...departments, { ...departments[0], id: "ambiguous" }], [], "c1", true).errors.length, 1);
assert.deepEqual(contactCustodians(duplicatePeople, "c1", true).map(row => row.id), ["p1", "p3"]);
console.log("Contact registration: 42 assertions passed for normalization, holders, shared use, company-prioritized batch matching and role boundaries.");
